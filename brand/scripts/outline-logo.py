"""Writes the Beni Bul logo with the wordmark converted to paths, so it needs no font, and the
print template for the 70 x 70 mm sticker that WaveService fills with each tag's QR code.

Needs fontTools (pip install fonttools). Run from the repo root:
    python brand/scripts/outline-logo.py

Output: brand/logo/*-outlined.svg, backend/public/img/beni-bul-logo*.svg (for the visitor page) and
backend/resources/stickers/sticker-70.svg (for the wave package).
"""
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
FONTS = ROOT / 'mobile/node_modules/@expo-google-fonts/manrope'
NAVY, SIGNAL, WHITE = '#14213D', '#FF6B2C', '#FFFFFF'
SIZE = 52  # locked wordmark size (brand/README.md)



class Face:
    def __init__(self, file):
        self.font = TTFont(FONTS / file)
        self.glyphs = self.font.getGlyphSet()
        self.cmap = self.font.getBestCmap()
        self.upm = self.font['head'].unitsPerEm

    def advance(self, text, size):
        return sum(self.font['hmtx'][self.cmap[ord(c)]][0] for c in text) * size / self.upm

    def path(self, text, x, baseline, size, anchor='start'):
        scale = size / self.upm
        if anchor == 'end':
            x -= self.advance(text, size)
        elif anchor == 'middle':
            x -= self.advance(text, size) / 2
        pen = SVGPathPen(self.glyphs)
        for c in text:
            name = self.cmap[ord(c)]
            # Font units are y-up; SVG is y-down.
            self.glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x, baseline)))
            x += self.font['hmtx'][name][0] * scale
        return pen.getCommands()


BOLD = Face('700Bold/Manrope_700Bold.ttf')
EXTRABOLD = Face('800ExtraBold/Manrope_800ExtraBold.ttf')


def text_path(text, x, baseline, anchor='start'):
    return BOLD.path(text, x, baseline, SIZE, anchor)


WORDS = text_path('beni', 12, 100) + ' ' + text_path('bul', 268, 120, 'end')


def mark(ink, accent):
    return f'''<g fill="none" stroke="{ink}" stroke-width="16" stroke-linecap="round">
    <line x1="14" y1="120" x2="110" y2="120"/>
    <circle cx="44" cy="150" r="30"/>
    <line x1="170" y1="60" x2="266" y2="60"/>
    <circle cx="236" cy="30" r="30"/>
  </g>
  <line x1="127" y1="108" x2="153" y2="72" stroke="{accent}" stroke-width="5" stroke-linecap="round"/>
  <g fill="{accent}"><circle cx="127" cy="108" r="7"/><circle cx="153" cy="72" r="7"/></g>
'''


def svg(ink, accent, words=True):
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="-4 -18 288 216" width="288" height="216" role="img" aria-label="beni bul">\n  '
            + mark(ink, accent) + (f'  <path fill="{ink}" d="{WORDS}"/>\n' if words else '') + '</svg>\n')


# Sticker, 70 x 70 mm, in millimetres, with 2 mm bleed. Layout approved in chat on 2026-11-09 (square version 1:
# navy band with the white logo, QR in the middle, call to action under it, no serial on the face).
# WaveService replaces <!--QR--> with the tag's QR code; keep QR_BOX in sync with StickerRenderer::QR_BOX.
STICKER_CTA = 'Okut, sahibine ulaş'
LOGO_SCALE = 13 / 196  # the logo's content is 196 units tall; 13 mm in the band
QR_BOX = (15, 21, 40)  # x, y, size in mm, including the QR's own white quiet zone


def sticker():
    tx, ty = 35 - 140 * LOGO_SCALE, 9.25 - 90 * LOGO_SCALE
    cta = EXTRABOLD.path(STICKER_CTA, 35, 66.3, 4.6, 'middle')
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- Beni Bul sticker, 70 x 70 mm finished size, 2 mm bleed on every side (artboard 74 x 74 mm).
     The CutContour layer is the die line (rounded square, 4.5 mm corners); it must not be printed.
     Generated by brand/scripts/outline-logo.py; text is outlined, no fonts needed. -->
<svg xmlns="http://www.w3.org/2000/svg" width="74mm" height="74mm" viewBox="-2 -2 74 74">
  <rect id="background" x="-2" y="-2" width="74" height="74" fill="{WHITE}"/>
  <rect id="band" x="-2" y="-2" width="74" height="20.5" fill="{NAVY}"/>
  <g id="logo" transform="translate({tx:.4f} {ty:.4f}) scale({LOGO_SCALE:.6f})">
    {mark(WHITE, SIGNAL)}    <path fill="{WHITE}" d="{WORDS}"/>
  </g>
  <!--QR-->
  <path id="call-to-action" fill="{NAVY}" d="{cta}"/>
  <rect id="CutContour" x="0" y="0" width="70" height="70" rx="4.5" fill="none" stroke="#EC008C" stroke-width="0.25"/>
</svg>
'''


outputs = {
    ROOT / 'brand/logo/beni-bul-logo-outlined.svg': svg(NAVY, SIGNAL),
    ROOT / 'brand/logo/beni-bul-logo-white-outlined.svg': svg(WHITE, SIGNAL),
    ROOT / 'brand/logo/beni-bul-logo-mono-outlined.svg': svg(NAVY, NAVY),
    ROOT / 'backend/public/img/beni-bul-logo.svg': svg(NAVY, SIGNAL),
    ROOT / 'backend/public/img/beni-bul-logo-white.svg': svg(WHITE, SIGNAL),
    ROOT / 'backend/resources/stickers/sticker-70.svg': sticker(),
}
for path, content in outputs.items():
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding='utf-8', newline='\n')
    print(f'wrote {path.relative_to(ROOT)} ({len(content)} bytes)')
